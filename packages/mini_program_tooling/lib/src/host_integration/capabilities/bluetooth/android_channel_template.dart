        }
        private fun notification(value: BluetoothGatt, c: BluetoothGattCharacteristic, bytes: ByteArray) {
            // No history buffer: at most one pending main-thread delivery per characteristic.
            val id = key(c)
            synchronized(lastNotification) {
                val now = SystemClock.elapsedRealtime()
                val previous = lastNotification[id] ?: return
                if (now - previous < 100 || !scheduledNotifications.add(id)) return
                lastNotification[id] = now
            }
            handler.post {
                synchronized(lastNotification) { scheduledNotifications.remove(id) }
                if (gatt !== value || !subscriptions.contains(id)) return@post
                if (bytes.size > maxValueBytes) { release(); return@post }
                emit("notification", valueData(c, bytes))
            }
        }
    }
    private fun closeGatt() {
