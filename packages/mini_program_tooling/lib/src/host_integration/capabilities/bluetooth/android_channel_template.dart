                if (bytes.size > maxValueBytes) { failPending("limit_exceeded"); return@post }
                complete(valueData(c, bytes))
            }
        }
        override fun onCharacteristicWrite(value: BluetoothGatt, c: BluetoothGattCharacteristic, status: Int) {
            handler.post {
                if (gatt !== value || pending?.action != "bluetooth.write" || pending?.characteristic !== c) return@post
                if (status != BluetoothGatt.GATT_SUCCESS) { failPending("operation_failed"); return@post }
                complete(mapOf("bytesWritten" to ((pending!!.args["valueHex"] as String).length / 2)))
            }
        }
        override fun onDescriptorWrite(value: BluetoothGatt, descriptor: BluetoothGattDescriptor, status: Int) {
            handler.post {
                val operation = pending
                if (gatt !== value || operation == null || operation.action !in setOf("bluetooth.subscribe", "bluetooth.unsubscribe") || operation.characteristic !== descriptor.characteristic || descriptor.uuid != CCCD) return@post
                if (status != BluetoothGatt.GATT_SUCCESS) { failPending("operation_failed"); release(); return@post }
                val id = key(descriptor.characteristic)
                if (operation.subscribe) {
                    subscriptions.add(id)
                    synchronized(lastNotification) { lastNotification[id] = -100L }
                } else {
                    subscriptions.remove(id)
                    synchronized(lastNotification) { lastNotification.remove(id); scheduledNotifications.remove(id) }
                }
                complete(mapOf("subscribed" to operation.subscribe))
            }
        }
        override fun onCharacteristicChanged(value: BluetoothGatt, c: BluetoothGattCharacteristic, bytes: ByteArray) = notification(value, c, bytes.copyOf())
        override fun onCharacteristicChanged(value: BluetoothGatt, c: BluetoothGattCharacteristic) {
