String buildAndroidNfcChannel(String packageName) =>
    _source.replaceAll('__PACKAGE__', packageName);

const _source = r'''
package __PACKAGE__

import android.app.Activity
import android.app.Application
import android.content.Context
import android.nfc.NdefRecord
import android.nfc.NfcAdapter
import android.nfc.Tag
import android.nfc.TagLostException
import android.nfc.tech.Ndef
import android.os.Bundle
import android.os.Handler
import android.os.Looper
import io.flutter.embedding.engine.FlutterEngine
import io.flutter.embedding.engine.plugins.FlutterPlugin
import io.flutter.embedding.engine.plugins.activity.ActivityAware
import io.flutter.embedding.engine.plugins.activity.ActivityPluginBinding
import io.flutter.plugin.common.MethodCall
import io.flutter.plugin.common.MethodChannel
import java.nio.ByteBuffer
import java.nio.charset.Charset
import java.nio.charset.CodingErrorAction
import java.util.concurrent.ArrayBlockingQueue
import java.util.concurrent.SynchronousQueue
import java.util.concurrent.ThreadPoolExecutor
import java.util.concurrent.TimeUnit
import java.util.concurrent.atomic.AtomicBoolean
import java.util.concurrent.atomic.AtomicReference

// Generated by mini_program_tooling. Do not edit.
// One foreground NDEF read. Tag objects, identifiers and raw bytes stay native.
internal class MiniProgramNfcChannel : FlutterPlugin, ActivityAware,
    MethodChannel.MethodCallHandler, Application.ActivityLifecycleCallbacks {
    companion object {
        // Method calls, Activity callbacks and ownership changes run on the main thread.
        private var owner: MiniProgramNfcChannel? = null
        private val workerBusy = AtomicBoolean(false)
        private val io = ThreadPoolExecutor(0, 1, 30, TimeUnit.SECONDS, SynchronousQueue<Runnable>(),
            { work -> Thread(work, "MiniProgramNfcRead").apply { isDaemon = true } })
        // Closing on a different worker cancels blocking tag I/O without blocking Flutter.
        private val cleanup = ThreadPoolExecutor(0, 1, 30, TimeUnit.SECONDS, ArrayBlockingQueue<Runnable>(1),
            { work -> Thread(work, "MiniProgramNfcClose").apply { isDaemon = true } })
        fun register(engine: FlutterEngine) {
            if (!engine.plugins.has(MiniProgramNfcChannel::class.java)) engine.plugins.add(MiniProgramNfcChannel())
        }
    }
    private val handler = Handler(Looper.getMainLooper())
    private var context: Context? = null
    private var activity: Activity? = null
    private var foreground = false
    private var channel: MethodChannel? = null
    private var pending: Pending? = null
    private class Pending(val appId: String, val sessionId: String, val result: MethodChannel.Result,
        val allowed: Set<String>, val maxRecords: Int, val maxBytes: Int) {
        @Volatile var cancelled = false
        val tagDelivered = AtomicBoolean(false)
        var reading = false
        var timeout: Runnable? = null
        val technology = AtomicReference<Ndef?>(null)
    }
    private class NfcFailure(val suffix: String) : RuntimeException()

    override fun onAttachedToEngine(value: FlutterPlugin.FlutterPluginBinding) {
        context = value.applicationContext
        channel = MethodChannel(value.binaryMessenger, "mini_program/nfc").also { it.setMethodCallHandler(this) }
    }
    override fun onDetachedFromEngine(value: FlutterPlugin.FlutterPluginBinding) {
        finish(error = "request_cancelled"); detachActivity()
        channel?.setMethodCallHandler(null); channel = null; context = null
    }
    override fun onAttachedToActivity(value: ActivityPluginBinding) {
        activity = value.activity; foreground = false
        value.activity.application.registerActivityLifecycleCallbacks(this)
    }
    private fun detachActivity() {
        activity?.application?.unregisterActivityLifecycleCallbacks(this)
        activity = null; foreground = false
    }
    override fun onDetachedFromActivityForConfigChanges() { finish(error = "request_cancelled"); detachActivity() }
    override fun onReattachedToActivityForConfigChanges(value: ActivityPluginBinding) = onAttachedToActivity(value)
    override fun onDetachedFromActivity() { finish(error = "request_cancelled"); detachActivity() }
    private fun adapter(): NfcAdapter? = context?.let { NfcAdapter.getDefaultAdapter(it) }
    private fun active(): Boolean = foreground && activity?.isFinishing == false && activity?.isDestroyed == false
    private fun validIdentity(value: Any?): Boolean = value is String && value.length in 1..200 &&
        !value.any { it.code < 32 || it.code in 127..159 }
    private fun integer(value: Any?, fallback: Int, min: Int, max: Int): Int {
        val number = value ?: fallback
        require(number is Int && number in min..max)
        return number
    }
    private fun failure(result: MethodChannel.Result, suffix: String) {
        result.error("nfc_$suffix", "Android NFC operation did not complete ($suffix).", null)
    }
    override fun onMethodCall(call: MethodCall, result: MethodChannel.Result) {
        val args = call.arguments as? Map<*, *>
        if (args == null || !validIdentity(args["appId"]) || !validIdentity(args["sessionId"])) {
            failure(result, "invalid_request"); return
        }
        val keys = if (call.method == "nfc.read") setOf("appId", "sessionId", "timeoutMs", "allowedRecordTypes", "maxRecords", "maxMessageBytes")
            else setOf("appId", "sessionId")
        if (args.keys.any { it !in keys }) { failure(result, "invalid_request"); return }
        if (call.method == "release") {
            val operation = pending
            if (operation != null && operation.appId == args["appId"] && operation.sessionId == args["sessionId"]) finish(error = "request_cancelled")
            result.success(null); return
        }
        if (!active()) { failure(result, "foreground_required"); return }
        try {
            val adapter = adapter()
            if (call.method == "nfc.getState") {
                result.success(mapOf("supported" to (adapter != null), "enabled" to (adapter?.isEnabled == true))); return
            }
            if (call.method != "nfc.read") { failure(result, "invalid_request"); return }
            val timeout = integer(args["timeoutMs"], 15000, 1000, 30000)
            val maxRecords = integer(args["maxRecords"], 8, 1, 16)
            val maxBytes = integer(args["maxMessageBytes"], 4096, 1, 8192)
            val types = args["allowedRecordTypes"] ?: listOf("text", "uri")
            require(types is List<*> && types.size in 1..2 && types.all { it == "text" || it == "uri" })
            if (pending != null) { failure(result, "request_in_progress"); return }
            if (owner != null || workerBusy.get()) { failure(result, "in_use"); return }
            if (adapter == null) { failure(result, "unavailable"); return }
            if (!adapter.isEnabled) { failure(result, "disabled"); return }
            val operation = Pending(args["appId"] as String, args["sessionId"] as String,
                result, types.map { it as String }.toSet(), maxRecords, maxBytes)
            pending = operation; owner = this
            operation.timeout = Runnable { if (pending === operation) finish(error = "timeout") }
                .also { handler.postDelayed(it, timeout.toLong()) }
            adapter.enableReaderMode(activity!!, { tag ->
                if (!operation.cancelled && operation.tagDelivered.compareAndSet(false, true)) {
                    handler.post { discovered(operation, tag) }
                }
            },
                NfcAdapter.FLAG_READER_NFC_A or NfcAdapter.FLAG_READER_NFC_B or
                NfcAdapter.FLAG_READER_NFC_F or NfcAdapter.FLAG_READER_NFC_V, null)
        } catch (_: IllegalArgumentException) { failCall(result, "invalid_request") }
        catch (_: SecurityException) { failCall(result, "permission_denied") }
        catch (_: Exception) { failCall(result, "operation_failed") }
    }
    private fun failCall(result: MethodChannel.Result, suffix: String) {
        if (pending?.result === result) finish(error = suffix) else failure(result, suffix)
    }
    private fun discovered(operation: Pending, tag: Tag) {
        if (pending !== operation || operation.reading || operation.cancelled || !active()) return
        operation.reading = true
        if (!workerBusy.compareAndSet(false, true)) { finish(error = "in_use"); return }
        try {
            io.execute {
                var technology: Ndef? = null
                var data: Map<String, Any>? = null
                var error: String? = null
                try {
                    if (operation.cancelled) throw NfcFailure("request_cancelled")
                    technology = Ndef.get(tag) ?: throw NfcFailure("unsupported_tag")
                    operation.technology.set(technology)
                    if (operation.cancelled) throw NfcFailure("request_cancelled")
                    technology.connect()
                    if (operation.cancelled) throw NfcFailure("request_cancelled")
                    val message = technology.ndefMessage ?: throw NfcFailure("unsupported_tag")
                    if (message.byteArrayLength !in 1..operation.maxBytes) throw NfcFailure("limit_exceeded")
                    val records = message.records
                    if (records.isEmpty()) throw NfcFailure("invalid_data")
                    if (records.size > operation.maxRecords) throw NfcFailure("limit_exceeded")
                    var bytes = 0
                    val values = records.map { record ->
                        val value = decode(record, operation.allowed)
                        bytes += if (value["type"] == "text") (value["text"] as String).toByteArray(Charsets.UTF_8).size + (value["language"] as String).length
                            else (value["uri"] as String).toByteArray(Charsets.UTF_8).size
                        if (bytes > operation.maxBytes) throw NfcFailure("limit_exceeded")
                        value
                    }
                    data = mapOf("records" to values)
                } catch (failure: NfcFailure) { error = failure.suffix }
                catch (_: TagLostException) { error = "tag_lost" }
                catch (_: android.nfc.FormatException) { error = "invalid_data" }
                catch (_: java.nio.charset.CharacterCodingException) { error = "invalid_data" }
                catch (_: SecurityException) { error = "permission_denied" }
                catch (_: Exception) { error = "operation_failed" }
                finally {
                    operation.technology.compareAndSet(technology, null)
                    try { technology?.close() } catch (_: Exception) {}
                    workerBusy.set(false)
                }
                handler.post { if (pending === operation && !operation.cancelled) finish(data = data, error = error) }
            }
        } catch (_: java.util.concurrent.RejectedExecutionException) {
            workerBusy.set(false); finish(error = "in_use")
        }
    }
    private fun decode(record: NdefRecord, allowed: Set<String>): Map<String, Any> {
        if (record.tnf != NdefRecord.TNF_WELL_KNOWN) throw NfcFailure("unsupported_record")
        val payload = record.payload
        if (record.type.contentEquals(NdefRecord.RTD_TEXT)) {
            if (!allowed.contains("text")) throw NfcFailure("unsupported_record")
            if (payload.isEmpty()) throw NfcFailure("invalid_data")
            val status = payload[0].toInt() and 255
            val length = status and 63
            if (status and 64 != 0 || payload.size < 1 + length) throw NfcFailure("invalid_data")
            val languageBytes = payload.copyOfRange(1, 1 + length)
            if (languageBytes.any { it.toInt() !in 0..127 }) throw NfcFailure("invalid_data")
            val language = String(languageBytes, Charsets.US_ASCII)
            if (!language.matches(Regex("[a-zA-Z0-9-]*"))) throw NfcFailure("invalid_data")
            val charset = if (status and 128 == 0) Charsets.UTF_8 else Charsets.UTF_16
            val text = strictDecode(payload.copyOfRange(1 + length, payload.size), charset)
            checkText(text, 4096)
            return mapOf("type" to "text", "text" to text, "language" to language)
        }
        if (record.type.contentEquals(NdefRecord.RTD_URI)) {
            if (!allowed.contains("uri")) throw NfcFailure("unsupported_record")
            if (payload.isEmpty() || (payload[0].toInt() and 255) > 35) throw NfcFailure("invalid_data")
            strictDecode(payload.copyOfRange(1, payload.size), Charsets.UTF_8)
            val uri = record.toUri() ?: throw NfcFailure("invalid_data")
            val text = uri.toString()
            checkText(text, 2048)
            if (uri.scheme != "https" || uri.host.isNullOrEmpty() || !uri.userInfo.isNullOrEmpty() ||
                text.any { it.isWhitespace() || it == '\\' || it.code < 32 || it.code in 127..159 } ||
                Regex("%(?:0[0-9a-f]|1[0-9a-f]|7f)", RegexOption.IGNORE_CASE).containsMatchIn(text)) {
                throw NfcFailure("invalid_data")
            }
            return mapOf("type" to "uri", "uri" to text)
        }
        throw NfcFailure("unsupported_record")
    }
    private fun strictDecode(bytes: ByteArray, charset: Charset): String = charset.newDecoder()
        .onMalformedInput(CodingErrorAction.REPORT).onUnmappableCharacter(CodingErrorAction.REPORT)
        .decode(ByteBuffer.wrap(bytes)).toString()
    private fun checkText(value: String, limit: Int) {
        if (value.length > limit || value.toByteArray(Charsets.UTF_8).size > limit) throw NfcFailure("limit_exceeded")
        if (value.any { it.code in 0..8 || it.code in 11..12 || it.code in 14..31 || it.code in 127..159 }) throw NfcFailure("invalid_data")
    }
    private fun finish(data: Map<String, Any>? = null, error: String? = null) {
        val operation = pending ?: return
        pending = null; operation.cancelled = true
        operation.timeout?.let { handler.removeCallbacks(it) }
        try { activity?.let { adapter()?.disableReaderMode(it) } } catch (_: Exception) {}
        if (owner === this) owner = null
        operation.technology.getAndSet(null)?.let { technology ->
            try { cleanup.execute { try { technology.close() } catch (_: Exception) {} } }
            catch (_: java.util.concurrent.RejectedExecutionException) { /* Read worker also closes in finally. */ }
        }
        if (error != null) failure(operation.result, error)
        else if (data != null) operation.result.success(data)
        else failure(operation.result, "operation_failed")
    }
    override fun onActivityResumed(value: Activity) { if (value === activity) foreground = true }
    override fun onActivityPaused(value: Activity) { if (value === activity) { foreground = false; finish(error = "request_cancelled") } }
    override fun onActivityStopped(value: Activity) { if (value === activity) { foreground = false; finish(error = "request_cancelled") } }
    override fun onActivityDestroyed(value: Activity) { if (value === activity) finish(error = "request_cancelled") }
    override fun onActivityCreated(value: Activity, state: Bundle?) {}
    override fun onActivityStarted(value: Activity) {}
    override fun onActivitySaveInstanceState(value: Activity, state: Bundle) {}
}
''';
