const systemCapabilities = {
  'clipboard',
  'vibration',
  'phone',
  'maps',
  'bluetooth',
  'nfc',
};

/// Builds and validates the entire install plan before touching host files.
Future<MiniProgramHostCapabilityInitResult> initializeSystemCapability(
  MiniProgramHostCapabilityInitRequest request,
) async {
  final feature = request.capability.trim().toLowerCase();
  final platform = request.platform.trim().toLowerCase();
  if (!systemCapabilities.contains(feature) || platform != 'android') {
    throw const MiniProgramHostCapabilityException(
      'System capabilities support Android only.',
    );
  }
  final title = '${feature[0].toUpperCase()}${feature.substring(1)}';
  final root = p.normalize(p.absolute(request.projectRootPath));
  final pubspec = File(p.join(root, 'pubspec.yaml'));
  if (!await pubspec.exists() ||
      !RegExp(
        r'^\s*flutter\s*:\s*$',
        multiLine: true,
      ).hasMatch(await pubspec.readAsString())) {
    throw const MiniProgramHostCapabilityException(
      'Capability installation requires a Flutter host.',
    );
  }
  final integration = p.join(root, 'lib', 'mini_program');
  final hostSetup = File(p.join(integration, 'mini_program_host_setup.dart'));
  final runtimeSetup = File(
    p.join(integration, 'mini_program_runtime_setup.dart'),
  );
  final kotlinRoot = Directory(
    p.join(root, 'android', 'app', 'src', 'main', 'kotlin'),
  );
  if (!await hostSetup.exists() ||
      !await runtimeSetup.exists() ||
      !await kotlinRoot.exists()) {
    throw const MiniProgramHostCapabilityException(
      'Run embed init in an Android Flutter host first.',
    );
  }
  final activities = await kotlinRoot
      .list(recursive: true, followLinks: false)
      .where((f) => f is File && p.basename(f.path) == 'MainActivity.kt')
      .cast<File>()
      .toList();
  if (activities.length != 1) {
    throw const MiniProgramHostCapabilityException(
      'Expected one Kotlin MainActivity.kt.',
    );
  }
  final main = activities.single;
  final mainSource = await main.readAsString();
  final packageName = RegExp(
    r'^\s*package\s+([A-Za-z_][A-Za-z0-9_.]*)\s*$',
    multiLine: true,
  ).firstMatch(mainSource)?.group(1);
  if (packageName == null) {
    throw const MiniProgramHostCapabilityException(
      'Could not read the Kotlin package.',
    );
  }
  final native = await buildAndroidNativeIntegrationEdit(
    mainActivityFile: main,
    packageName: packageName,
    mainActivitySource: mainSource,
    registration: 'MiniProgram${title}Channel.register(flutterEngine)',
  );
  final channel = native.paths.generatedFile(
    feature,
    'MiniProgram${title}Channel.kt',
  );
  final migration = await resolveAndroidGeneratedSource(
    generatedFile: channel,
    legacyFile: native.paths.legacyFile('MiniProgram${title}Channel.kt'),
    requiredMarker: 'class MiniProgram${title}Channel',
    toolingGeneratedMarker:
        '// Generated by mini_program_tooling. Do not edit.',
    buildSource: () => feature == 'nfc'
        ? buildAndroidNfcChannel(packageName)
        : feature == 'bluetooth'
        ? buildAndroidBluetoothChannel(packageName)
        : feature == 'maps'
        ? buildAndroidMapsChannel(packageName)
        : buildAndroidSystemChannel(packageName, feature),
  );
  final provider = File(
    p.join(integration, 'app_android_${feature}_provider.dart'),
  );
  final providerSource = await provider.exists()
      ? await provider.readAsString()
      : null;
  if (providerSource != null &&
      !providerSource.contains('class AppAndroid${title}Provider')) {
    throw MiniProgramHostCapabilityException(
      'Refusing to overwrite unrecognized host file ${provider.path}.',
    );
  }
  final hostSource = await hostSetup.readAsString();
  final runtimeSource = await runtimeSetup.readAsString();
  final nextHost = patchSystemHostSetup(hostSource, feature);
  final nextRuntime = patchSystemRuntimeSetup(runtimeSource, feature);
  final manifest = File(
    p.join(root, 'android', 'app', 'src', 'main', 'AndroidManifest.xml'),
  );
  final manifestSource = feature == 'bluetooth' || feature == 'nfc'
      ? await manifest.readAsString()
      : null;
  final nextManifest = manifestSource == null
      ? null
      : feature == 'nfc'
      ? patchNfcManifest(manifestSource)
      : patchBluetoothManifest(manifestSource);
  return writeCapabilityFiles(
    projectRootPath: root,
    capability: feature,
    platform: platform,
    writes: {
      if (nextManifest != null && nextManifest != manifestSource)
        manifest.path: nextManifest,
      ...native.writes,
      ...migration.writes,
      if (providerSource == null)
        provider.path: feature == 'nfc'
            ? androidNfcProviderSource
            : feature == 'bluetooth'
            ? androidBluetoothProviderSource
            : feature == 'maps'
            ? buildAndroidMapsProvider()
            : buildAndroidSystemProvider(feature),
      if (nextHost != hostSource) hostSetup.path: nextHost,
      if (nextRuntime != runtimeSource) runtimeSetup.path: nextRuntime,
    },
    deletes: migration.deletes,
  );
}
