const _phone = r'''
            if (call.method != "openDialer") { result.notImplemented(); return }
            val raw = call.argument<String>("number")
            if (raw == null || raw.length > 64 || !Regex("^[+0-9(). -]+$").matches(raw)) {
                result.error("phone_invalid_request", "Invalid ordinary phone number.", null)
                return
            }
            val number = raw.replace(Regex("[(). -]"), "")
            if (!Regex("^\\+?[0-9]{1,32}$").matches(number)) {
                result.error("phone_invalid_request", "Invalid ordinary phone number.", null)
                return
            }
            try {
                current.startActivity(Intent(Intent.ACTION_DIAL, Uri.fromParts("tel", number, null)))
                result.success(null)
            } catch (_: ActivityNotFoundException) {
                result.error("phone_unavailable", "No system dialer is installed.", null)
            } catch (_: SecurityException) {
                result.error("phone_unavailable", "The system dialer is unavailable.", null)
            }
''';
