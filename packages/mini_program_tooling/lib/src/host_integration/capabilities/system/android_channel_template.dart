                    if (maximum == null || maximum !in 1..32768) {
                        result.error("clipboard_invalid_request", "Invalid clipboard text limit.", null)
                        return
                    }
                    val clip = manager.primaryClip
                    val item = if (clip != null && clip.itemCount > 0 &&
