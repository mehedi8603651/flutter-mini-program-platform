            val effect = call.argument<String>("effect")
            val feedback = when (effect) {
                "light" -> HapticFeedbackConstants.KEYBOARD_TAP
                "medium" -> if (Build.VERSION.SDK_INT >= 23) HapticFeedbackConstants.CONTEXT_CLICK else HapticFeedbackConstants.KEYBOARD_TAP
